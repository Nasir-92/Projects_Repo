    //Atributo de tipo dictionary con clave valor donde se va a añadir cada botón
    //clickeado junto con su proceso.Esto se hará dentro de cada evento click
    private Map<JButton, Process> procesosActivos = new HashMap<>();

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        //Recorremos todos los procesos
        for (Map.Entry<JButton, Process> elementoPar : procesosActivos.entrySet()) {

            JButton boton = elementoPar.getKey();
            Process proceso = elementoPar.getValue();

            // Si ya ha terminado, habilitamos su botón
            if (!proceso.isAlive()) {

                boton.setEnabled(true);
            }
        }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private Process consolaProcess;
    private void btnConsolaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsolaActionPerformed
        String comando = "cmd /c start cmd";
        ProcessBuilder b = new ProcessBuilder(comando.split("\\s"));

        try {
            consolaProcess = b.start();
            btnConsola.setEnabled(false);
            procesosActivos.put(btnConsola, consolaProcess);

            //Si el checkBox está seleccionado
            if (chkRedirigir.isSelected()) {

                // 🔹 Guardar en archivo
                PrintWriter pr = new PrintWriter(
                        new BufferedWriter(
                                new OutputStreamWriter(
                                        new FileOutputStream("salida.txt", true),
                                        StandardCharsets.UTF_8)));

                pr.println("✔ Consola lanzada correctamente");
                pr.close();

            } else {

                jTextArea1.append("✔ Consola lanzada correctamente\n");

            }

        } catch (IOException ex) {

            // Hacemos el mismo control del checkBox en el catch
            if (chkRedirigir.isSelected()) {
                try {
                    // 🔹 Guardar en archivo
                    PrintWriter pr = new PrintWriter(
                            new BufferedWriter(
                                    new OutputStreamWriter(
                                            new FileOutputStream("salida.txt", true),
                                            StandardCharsets.UTF_8)));

                    pr.println(ex.getMessage());

                } catch (FileNotFoundException ex1) {

                    jTextArea1.append("❌ ERROR al guardar en salida.txt: " + ex1.getMessage() + "\n");
                }

            } else {
                jTextArea1.append("❌ ERROR: " + ex.getMessage() + "\n");
            }
        }
    }//GEN-LAST:event_btnConsolaActionPerformed

