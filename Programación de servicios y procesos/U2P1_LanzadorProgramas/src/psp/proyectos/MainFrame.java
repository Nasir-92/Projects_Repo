    private void btnEjecutarComandoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEjecutarComandoActionPerformed

        String comando = txtComando.getText();

        if (comando.isEmpty()) {

            jTextArea1.append("Debe de introducir un comando para ejecutar");
        } else {

            String comandoComplet = "cmd /c " + comando;
            ProcessBuilder b = new ProcessBuilder(comandoComplet.split("\\s"));
            try {
                Process p = b.start();

                BufferedReader salida = new BufferedReader(
                        new InputStreamReader(p.getInputStream()));
                BufferedReader error = new BufferedReader(
                        new InputStreamReader(p.getErrorStream()));

                String linea;

                if (chkRedirigir.isSelected()) {

                    PrintWriter pr = new PrintWriter(new BufferedWriter(
                            new OutputStreamWriter(
                                    new FileOutputStream("salida.txt", true), StandardCharsets.UTF_8)));
                    
                    while ((linea = salida.readLine()) != null) {

                        pr.println(linea);

                    }
                    while ((linea = error.readLine()) != null) {

                 

                        pr.println(linea);

                    }
                    pr.close();
                } else {

                    while ((linea = salida.readLine()) != null) {

                        jTextArea1.append(linea + "\n");
                    }
                    while ((linea = error.readLine()) != null) {

                        jTextArea1.append(linea + "\n");
                    }
                }

            } catch (IOException ex) {

                if (chkRedirigir.isSelected()) {
                    try {
                        PrintWriter pr = new PrintWriter(new BufferedWriter(
                                new OutputStreamWriter(
                                        new FileOutputStream("salida.txt", true), StandardCharsets.UTF_8)));

                        pr.println(ex.getMessage());
                        
                        pr.close();
                    } catch (FileNotFoundException ex1) {

                        jTextArea1.append("❌ ERROR al guardar en salida.txt: " + ex1.getMessage() + "\n");
                    }
                } else {

                    jTextArea1.append("❌ ERROR: " + ex.getMessage() + "\n");
                }
            }

        }


    }//GEN-LAST:event_btnEjecutarComandoActionPerformed

